// scripts/build-bookmarklet.mjs
// Shrinks scripts/nw-bookmarklet.js and writes it into lib/nwBookmarklet.ts as text, so the
// app can offer it as a bookmark. Run with `npm run build:bookmark` after editing the bookmark.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(path.join(root, 'scripts/nw-bookmarklet.js'), 'utf8');
const { code } = await esbuild.transform(source, { minify: true, target: 'es2019', charset: 'ascii' });

const out = `// lib/nwBookmarklet.ts
// GENERATED by scripts/build-bookmarklet.mjs from scripts/nw-bookmarklet.js. Don't edit by hand.
// The "Fill trolley from Homedash" bookmark, as text. Saved as a bookmark's address, it runs on
// newworld.co.nz in your own signed-in tab and adds the Homedash list to your trolley.

export const NW_BOOKMARKLET_CODE = ${JSON.stringify(code.trim())};

/** What goes in the bookmark's address box. */
export const NW_BOOKMARKLET_URL = 'javascript:' + encodeURIComponent(NW_BOOKMARKLET_CODE);
`;
writeFileSync(path.join(root, 'lib/nwBookmarklet.ts'), out);

// The same code as a userscript: with a userscript extension it runs by itself on New World,
// so there's no bookmark to tap. Served from the site as /homedash-newworld.user.js.
const userscript = `// ==UserScript==
// @name         Homedash: fill my New World trolley
// @namespace    homedash
// @version      ${new Date().toISOString().slice(0, 16).replace(/[-T:]/g, '.')}
// @description  When Homedash sends a shopping list to New World or PAK'nSAVE, adds it to your trolley. Does nothing on any other visit, and never orders or pays.
// @match        https://www.newworld.co.nz/*
// @match        https://www.paknsave.co.nz/*
// @run-at       document-start
// @inject-into  page
// @downloadURL  https://homedash-two.vercel.app/homedash-newworld.user.js
// @updateURL    https://homedash-two.vercel.app/homedash-newworld.user.js
// @grant        none
// @noframes
// ==/UserScript==

(function () {
var HOMEDASH_AUTO = true;
${code.trim()}
})();
`;
writeFileSync(path.join(root, 'public/homedash-newworld.user.js'), userscript);
console.log(`lib/nwBookmarklet.ts written (${code.length} characters)`);
